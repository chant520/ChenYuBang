package com.chenyubang.feature.review

/**
 * feature-review 模块占位：复习页面簇。
 *
 * 负责页面（信息架构 v1.2 §3 页面清单，路由键见开发规范 v1.4 §5.1）：
 *  - P11 复习队列（`review/queue`，全屏浮层；全局模式与单成语模式共用本页）
 *  - P12 复习小结（`review/summary`，全屏浮层）
 *
 * 模块职责：
 *  - 队列 = 全部 `state = 待复习` 的错题，按 `createdAt` 倒序；单成语模式按 `idiomId` 过滤，无内容时按钮置灰。
 *  - 页内「本轮范围」一行区分两种来源（全部待复习 / 只看「某成语」）。
 *  - 选完立即判分，判分区只说「与首次作答相同 / 不同」并附「本题未记录正确答案」，不渲染解析，同时写 `review_log`；不自动改 `state`（MVP 不引记忆算法）。
 *  - 退出中途二次确认；一轮结束进小结，题量 / 正确数 / 涉及成语列表与操作保持一致。
 *  - 连续答对的掌握状态提示（C9）只作进阶预留位，不在 MVP 实现。
 *
 * 依赖方向（开发规范 v1.4 §3 硬规则）：
 *  - 允许依赖：`:core-ui`（构件与令牌）、`:core-data`（错题与复习记录数据）。
 *  - 禁止依赖：任何其他 feature 模块——feature 之间不得互相依赖。
 *  - `:core-ui` 不得反向依赖本模块。
 *
 * TODO(P11–P12): 按路由表逐页接入界面与 ViewModel；
 * 视觉一律取 core-ui 令牌常量，禁止在页面里写颜色 / 字号 / 圆角 / 间距字面量。
 */
object ReviewFeature {
    /** 本模块负责的页面号，便于路由接线时核对归属（信息架构 v1.2 §3）。 */
    val OWNED_PAGES: List<String> = listOf("P11", "P12")
}
